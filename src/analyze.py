"""Recalculate official annual performance without mixing provincial aggregates."""
import csv
import hashlib
from decimal import Decimal

from src.common import PROCESSED, RAW, REPORTS, normalize_name, read_json, write_json

AGGREGATE = "Municipalities without targets"


def load_year(year):
    with (RAW / "ontario" / f"housing_{year}.csv").open(encoding="utf-8-sig", newline="") as stream:
        rows = [{k.strip(): v.strip() for k, v in row.items()} for row in csv.DictReader(stream)]
    result = []
    seen = set()
    for row in rows:
        name = row["Municipality"]
        key = normalize_name(name)
        if key in seen:
            raise ValueError(f"Duplicate municipality key: {name}")
        seen.add(key)
        target = int(row[f"Target for {year}"])
        progress = int(row[f"Total {year} housing progress"])
        if target <= 0 or progress < 0:
            raise ValueError(f"Invalid counts: {name}")
        percentage = Decimal(progress) * 100 / Decimal(target)
        published = Decimal(row[f"Progress % for {year}"].rstrip("%"))
        result.append({"year": year, "municipality": name, "municipality_key": key,
                       "scope": "aggregate_without_individual_targets" if name == AGGREGATE else "individual_target",
                       "target": target, "official_progress": progress,
                       "official_progress_pct": float(percentage), "met_100pct": progress >= target,
                       "published_progress_pct": float(published),
                       "percentage_reconciles": abs(percentage - published) <= Decimal("0.011"),
                       "published_status": row.get("Housing target status", row.get("Housing Target Status"))})
    return result


def main():
    manifest = read_json(RAW / "manifest.json")
    for key, entry in manifest.items():
        if hashlib.sha256((RAW / key).read_bytes()).hexdigest() != entry["sha256"]:
            raise ValueError(f"Snapshot checksum mismatch: {key}")
    all_rows = [row for year in (2023, 2024) for row in load_year(year)]
    diagnostics = [{"year": r["year"], "municipality": r["municipality"],
                    "published_pct": r["published_progress_pct"], "calculated_pct": r["official_progress_pct"]}
                   for r in all_rows if not r["percentage_reconciles"]]
    write_json(PROCESSED / "data_quality.json", {"percentage_discrepancies": diagnostics})
    PROCESSED.mkdir(parents=True, exist_ok=True)
    with (PROCESSED / "municipal_progress.csv").open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(all_rows[0]))
        writer.writeheader()
        writer.writerows(all_rows)
    summaries = {}
    report=["# Official annual target baseline","","Generated by `python -m src.analyze`. Measure: official annual progress >= 100% of the annual target.",""]
    for year in (2023, 2024):
        rows = [r for r in all_rows if r["year"] == year and r["scope"] == "individual_target"]
        aggregate = [r for r in all_rows if r["year"] == year and r["scope"] != "individual_target"]
        if len(rows) != 50 or len(aggregate) != 1:
            raise ValueError(f"Unexpected coverage in {year}: inspect source before publishing")
        met = [r for r in rows if r["met_100pct"]]
        provincial_target = {2023: 110000, 2024: 125000}[year]
        provincial_progress = sum(r["official_progress"] for r in rows + aggregate)
        summaries[year] = {
            "municipalities_with_targets": len(rows), "met_100pct": len(met), "below_100pct": len(rows) - len(met),
            "targeted_municipalities_progress": sum(r["official_progress"] for r in rows),
            "aggregate_without_individual_targets_progress": aggregate[0]["official_progress"],
            "province_official_progress": provincial_progress, "province_target": provincial_target,
            "province_progress_pct": provincial_progress / provincial_target * 100,
            "sum_csv_targets": sum(r["target"] for r in rows + aggregate),
        }
        s = summaries[year]
        report += [f"## {year}","",f"- {len(met)} of {len(rows)} municipalities reached 100%; {len(rows)-len(met)} fell below.",
            f"- Provincial official progress, including the aggregate row: {provincial_progress:,} / {provincial_target:,} ({s['province_progress_pct']:.2f}%).",
            f"- Sum of CSV targets: {s['sum_csv_targets']:,}; the provincial target stays separate to avoid rounding effects.","",
            "| Municipality | Annual target | Official progress | % of target |","|---|---:|---:|---:|"]
        report += [f"| {r['municipality']} | {r['target']} | {r['official_progress']} | {r['official_progress_pct']:.2f}% |"
            for r in sorted(rows,key=lambda r:r["official_progress_pct"],reverse=True)]
        report.append("")
    report += ["## Limitations","","Official totals combine housing-supply categories. They are not conventional CMHC starts alone or completed dwellings. The CSV does not provide municipal component breakdowns.","",
        "The Municipalities without targets aggregate enters only the provincial total, never a municipal ranking or denominator.","",
        "This baseline covers 2023/2024. Separate project modules document the partial 2025 funding evidence and CMHC residential series. See README.md and reports/research.md."]
    if diagnostics:
        report += ["", "## Source discrepancies", "", "The percentages below were recalculated from original counts without changing the source CSV:", ""]
        report += [f"- {d['year']} / {d['municipality']}: published {d['published_pct']:.2f}%; calculated {d['calculated_pct']:.4f}%." for d in diagnostics]
    write_json(PROCESSED / "summary.json", summaries)
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / "baseline.md").write_text("\n".join(report) + "\n", encoding="utf-8")
    print(summaries)


if __name__ == "__main__":
    main()

